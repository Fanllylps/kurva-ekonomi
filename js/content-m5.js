      <p>Pemerintah dapat menetapkan harga atau mengubah insentif melalui pajak dan subsidi. Tujuannya bisa melindungi konsumen, melindungi produsen, menambah penerimaan, atau mendorong aktivitas tertentu. Efek sampingnya tetap harus dihitung.</p>
