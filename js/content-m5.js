    <div class="cheat-sheet reveal">
      <div class="cheat-head">
        <span class="micro-label">Kartu ingat · pertemuan 05</span>
        <span class="cheat-code">E → SK + SP</span>
      </div>
      <div class="cheat-grid">
        <div><strong>Ekuilibrium</strong><p>Qd = Qs; membentuk Pe dan Qe.</p></div>
        <div><strong>Kekurangan barang</strong><p>Qd &gt; Qs (jumlah yang ingin dibeli lebih besar dari yang dijual), bukan surplus konsumen.</p></div>
        <div><strong>Surplus konsumen</strong><p>Kesediaan membayar − harga pasar; luas di atas Pe, di bawah D.</p></div>
        <div><strong>Surplus produsen</strong><p>Harga pasar − kesediaan minimum; luas di bawah Pe, di atas S.</p></div>
        <div><strong>HET</strong><p>Harga Eceran Tertinggi. Jika di bawah Pe: barang bisa kurang.</p></div>
        <div><strong>Harga dasar</strong><p>Batas minimum. Jika di atas Pe: kelebihan penawaran.</p></div>
      </div>
    </div>

