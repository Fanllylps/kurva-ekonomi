    <div class="prose-grid">
      <div class="prose reveal">
        <p>Dynamic pricing adalah strategi menetapkan harga secara fleksibel berdasarkan perubahan kondisi pasar. Harga yang sama tidak harus berlaku sepanjang hari untuk semua orang.</p>
        <p>Tiga faktor utamanya: <strong>supply–demand</strong>, <strong>harga kompetitor</strong>, dan <strong>waktu atau momen</strong>. Hotel menaikkan tarif saat kamar hampir habis; transportasi daring menaikkan tarif saat hujan dan permintaan melonjak.</p>
        <p>Namun, dynamic pricing bukan sihir. Ia membutuhkan data, aturan yang dapat dijelaskan, dan kehati-hatian agar konsumen tidak merasa diperlakukan tidak adil.</p>
      </div>
      <aside class="margin-note reveal">
        <span class="note-no">Istilah</span>
        <p><strong>Harga maksimum yang rela dibayar</strong> (reservation price) adalah batas tertinggi seorang konsumen bersedia bayar. Harga dinamis (dynamic pricing) mencoba menyesuaikan tarif dengan kondisi pada waktu dan kelompok pembeli tertentu.</p>
      </aside>
    </div>

